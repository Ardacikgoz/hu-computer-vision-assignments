def resultInf(results):
  p = results.box.p[0]
  r = results.box.r[0]
  map50 = results.box.map50
  map95 = results.box.map

  print('Results Of Test Set')
  print(f"Precision: {p:.3f}")
  print(f"Recall: {r:.3f}")
  print(f"F1-score: {2 * (p * r) / (p + r):.3f}")
  print(f"mAP@0.5: {map50:.3f}")
  print(f"mAP@0.5:0.95: {map95:.3f}")
  print(results.confusion_matrix.matrix)

def evaluateCounting(predicted_counts, ground_truth_counts):
    mse = mean_squared_error(ground_truth_counts, predicted_counts)
    exact_matches = sum([p == g for p, g in zip(predicted_counts, ground_truth_counts)])
    exact_match_accuracy = 100 * exact_matches / len(ground_truth_counts)

    print(f"Exact Match Accuracy: {exact_match_accuracy:.2f}%")
    print(f"Mean Squared Error: {mse:.4f}")

def get_ground_truth_counts(label_dir, image_names):
    counts = []
    for name in image_names:
        base_name = name.replace('.jpg', '').replace('.png', '')
        label_path = os.path.join(label_dir, base_name + '.txt')

        if os.path.exists(label_path):
            with open(label_path, 'r') as f:
                count = len(f.readlines())
        else:
            print(f"⚠️ Etiket bulunamadı: {label_path}")
            count = 0

        counts.append(count)
    return counts

def draw_boxes_comparison(prediction_obj, label_path, image_path):
    img = cv2.imread(image_path)
    img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    h, w, _ = img.shape

    img_pred = img.copy()
    img_gt = img.copy()

    if prediction_obj.boxes is not None:
        for box in prediction_obj.boxes:
            b = box.xyxy[0].cpu().numpy().astype(int)
            cv2.rectangle(img_pred, (b[0], b[1]), (b[2], b[3]), (255, 0, 0), 2)

    if os.path.exists(label_path):
        with open(label_path, 'r') as f:
            lines = f.readlines()
            for line in lines:
                parts = list(map(float, line.strip().split()))
                cls, cx, cy, bw, bh = parts
                x1 = int((cx - bw / 2) * w)
                y1 = int((cy - bh / 2) * h)
                x2 = int((cx + bw / 2) * w)
                y2 = int((cy + bh / 2) * h)
                cv2.rectangle(img_gt, (x1, y1), (x2, y2), (0, 255, 0), 2)

    plt.figure(figsize=(12, 6))
    plt.subplot(1, 2, 1)
    plt.imshow(img_gt)
    plt.title("Ground Truth")
    plt.axis("off")

    plt.subplot(1, 2, 2)
    plt.imshow(img_pred)
    plt.title("Prediction")
    plt.axis("off")

    plt.tight_layout()
    plt.show()

def createModelTrainAndTest(optimizer='Adam', learningRate=1e-4, batchSize=16, freezeOrNot=False, freezeValue=0,epochVal = 20,imgSize = 640):
    logging.getLogger("ultralytics").setLevel(logging.WARNING)  # Konsol çıktısını azalt

    model = YOLO('yolov8n.pt')

    runName = f"YOLO_lr{learningRate}_b{batchSize}_f{freezeValue}_e{epochVal}"

    train_kwargs = {
        'data': '/content/dataset_folder/dataset.yaml',
        'epochs': epochVal,
        'imgsz': imgSize,
        'batch': batchSize,
        'optimizer': optimizer,
        'lr0': learningRate,
        'verbose': False,
        'project': 'runs/detect',
        'name': runName
    }

    if freezeOrNot:
        train_kwargs['freeze'] = freezeValue

    model.train(**train_kwargs)

    val_metrics = model.val(data='dataset_folder/dataset.yaml', split='test')
    resultInf(val_metrics)

    predictions = model.predict(source='/content/dataset_folder/_backup_test_set/images/test', save=False)
    predicted_counts = [len(p.boxes.data) for p in predictions]

    for pred in predictions[:5]:
        img_path = pred.path
        label_path = img_path.replace('images', 'labels').replace('.png', '.txt')
        draw_boxes_comparison(pred, label_path, img_path)

    image_names = [os.path.basename(p.path) for p in predictions]
    gt_counts = get_ground_truth_counts('/content/dataset_folder/_backup_test_set/labels/test', image_names)
    print('predicteed car count in showing images', sum(predicted_counts[:5]))
    print('ground truth car count in showing images', sum(gt_counts[:5]))
    print('total predicted car count: ',sum(predicted_counts))
    print('total ground truth car count: ',sum(gt_counts))

    evaluateCounting(predicted_counts, gt_counts)

    result_image_path = f"runs/detect/{runName}/results.png"
    if os.path.exists(result_image_path):
        img = Image.open(result_image_path)
        plt.figure(figsize=(16, 12))
        plt.imshow(img)
        plt.axis('off')
        plt.title(f"Loss & Metrics - {runName}")
        plt.show()
    else:
        print("results.png not found.")

