class SimpleCNN(nn.Module):
    def __init__(self, num_classes=11, dropout_rate=0):
        super(SimpleCNN, self).__init__()

        self.features = nn.Sequential(
            nn.Conv2d(3, 32, kernel_size=3, padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(),
            nn.MaxPool2d(2, 2),

            nn.Conv2d(32, 64, kernel_size=3, padding=1),
            nn.BatchNorm2d(64),
            nn.ReLU(),
            nn.MaxPool2d(2, 2),

            nn.Conv2d(64, 128, kernel_size=3, padding=1),
            nn.BatchNorm2d(128),
            nn.ReLU(),
            nn.MaxPool2d(2, 2),

            nn.Conv2d(128, 256, kernel_size=3, padding=1),
            nn.BatchNorm2d(256),
            nn.ReLU(),
            nn.MaxPool2d(2, 2),

            nn.Conv2d(256, 512, kernel_size=3, padding=1),
            nn.BatchNorm2d(512),
            nn.ReLU(),
            nn.MaxPool2d(2, 2)
        )

        self.classifier = nn.Sequential(
            nn.Linear(512 * 7 * 7, 512),
            nn.ReLU(),
            nn.Dropout(p=dropout_rate),
            nn.Linear(512, num_classes)
        )

    def forward(self, x):
        x = self.features(x)
        x = x.view(x.size(0), -1)
        x = self.classifier(x)
        return x

"""The SimpleCNN class defines a deep Convolutional Neural Network (CNN) designed for an 11-class image classification task. The feature extractor part consists of 5 convolutional blocks, each including a Conv2D layer, Batch Normalization, a ReLU activation, and MaxPooling. This structure progressively processes the input 3-channel (RGB) images, extracting increasingly abstract features at each stage. The classifier part includes two fully connected layers: the first Linear layer reduces the 512×7×7 feature map to 512 units, followed by a ReLU activation and Dropout layer; the final Linear layer maps the features to 11 output classes. The model’s goal is to predict the class of each input image based on the high-level features learned. The dropout rate is adjustable and helps mitigate overfitting during training."""

class ResidualBlock(nn.Module):
    def __init__(self, in_channels, out_channels, downsample=False):
        super(ResidualBlock, self).__init__()
        stride = 2 if downsample else 1

        self.conv1 = nn.Conv2d(in_channels, out_channels, kernel_size=3, padding=1, stride=stride)
        self.bn1 = nn.BatchNorm2d(out_channels)
        self.relu = nn.ReLU()

        self.conv2 = nn.Conv2d(out_channels, out_channels, kernel_size=3, padding=1)
        self.bn2 = nn.BatchNorm2d(out_channels)

        self.downsample = downsample
        self.identity = nn.Sequential()
        if downsample or in_channels != out_channels:
            self.identity = nn.Sequential(
                nn.Conv2d(in_channels, out_channels, kernel_size=1, stride=stride),
                nn.BatchNorm2d(out_channels)
            )

    def forward(self, x):
        identity = self.identity(x)

        out = self.relu(self.bn1(self.conv1(x)))
        out = self.bn2(self.conv2(out))
        out += identity
        out = self.relu(out)

        return out

class ResidualCNN(nn.Module):
    def __init__(self, num_classes=11,dropout_rate = 0.0):
        super(ResidualCNN, self).__init__()
        self.layer1 = nn.Sequential(
            nn.Conv2d(3, 32, kernel_size=3, padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(),
            nn.MaxPool2d(2, 2)
        )

        self.res_block1 = ResidualBlock(32, 64, downsample=True)
        self.res_block2 = ResidualBlock(64, 128, downsample=True)
        self.res_block3 = ResidualBlock(128, 256, downsample=True)
        self.res_block4 = ResidualBlock(256, 512, downsample=True)

        self.classifier = nn.Sequential(
            nn.Linear(512 * 7 * 7, 512),
            nn.ReLU(),
            nn.Dropout(p=dropout_rate),
            nn.Linear(512, num_classes)
        )

    def forward(self, x):
        x = self.layer1(x)
        x = self.res_block1(x)
        x = self.res_block2(x)
        x = self.res_block3(x)
        x = self.res_block4(x)

        x = x.view(x.size(0), -1)
        x = self.classifier(x)
        return x

"""The ResidualCNN class implements a deep Convolutional Neural Network that leverages residual connections to improve learning for an 11-class image classification task. The network starts with an initial convolutional block that processes the 3-channel input image, followed by 4 stacked ResidualBlocks. Each residual block contains two convolutional layers with Batch Normalization and ReLU activations, along with a skip connection that allows the input to bypass these layers, effectively mitigating the vanishing gradient problem. Each block also applies downsampling (via stride=2) to reduce spatial dimensions while increasing feature depth, progressing from 32 to 512 channels. The classifier part includes two fully connected layers: the first reduces the flattened 512×7×7 feature map to 512 units with a ReLU and Dropout layer; the final layer outputs the class probabilities. By integrating skip connections and progressive downsampling, this architecture facilitates deeper learning and more robust feature extraction compared to a standard CNN."""

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

def train_model(model, train_loader, val_loader, lr=1e-3, num_epochs=50):
    model.to(device)
    criterion = nn.CrossEntropyLoss()
    optimizer = optim.Adam(model.parameters(), lr=lr)

    train_losses, val_losses = [], []
    train_accs, val_accs = [], []

    for epoch in range(num_epochs):
        model.train()
        correct, total, epoch_loss = 0, 0, 0
        for images, labels in train_loader:
            images, labels = images.to(device), labels.to(device)

            outputs = model(images)
            loss = criterion(outputs, labels)

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            epoch_loss += loss.item() * images.size(0)
            _, predicted = outputs.max(1)
            correct += predicted.eq(labels).sum().item()
            total += labels.size(0)

        train_loss = epoch_loss / total
        train_acc = correct / total
        train_losses.append(train_loss)
        train_accs.append(train_acc)

        # Validation
        model.eval()
        correct, total, val_loss = 0, 0, 0
        with torch.no_grad():
            for images, labels in val_loader:
                images, labels = images.to(device), labels.to(device)
                outputs = model(images)
                loss = criterion(outputs, labels)

                val_loss += loss.item() * images.size(0)
                _, predicted = outputs.max(1)
                correct += predicted.eq(labels).sum().item()
                total += labels.size(0)

        val_loss /= total
        val_acc = correct / total
        val_losses.append(val_loss)
        val_accs.append(val_acc)

        print(f"Epoch [{epoch+1}/{num_epochs}] "
              f"Train Loss: {train_loss:.4f}, Train Acc: {train_acc:.4f} | "
              f"Val Loss: {val_loss:.4f}, Val Acc: {val_acc:.4f}")

    return [train_losses, val_losses, train_accs, val_accs]

"""The train_model function trains a given PyTorch model using a specified training and validation data loader. It runs for a defined number of epochs (default 50), using the CrossEntropyLoss as the loss function and the Adam optimizer. In each epoch, it performs a full training loop (with gradient updates) and then evaluates the model on the validation set without updating weights. The function tracks and stores loss and accuracy metrics for both training and validation, printing a summary at the end of each epoch. Finally, it returns lists of losses and accuracies for further analysis or plotting.

In this study, I experimented with two different batch sizes (32 and 64) and three learning rates (1e-3, 1e-4, and 1e-5) to observe their impact on model performance. The batch sizes were chosen to balance between computational efficiency and stable gradient updates: a batch size of 32 is a common default that offers reliable performance, while 64 was tested to evaluate the effect of larger batches on convergence. For the learning rate, 1e-3 is a standard starting point for the Adam optimizer, while 1e-4 and 1e-5 were included to examine whether smaller learning rates provide better fine-grained updates and more stable training, especially in deeper models. These parameter combinations help identify optimal settings for achieving high validation accuracy and stable loss convergence.
"""

